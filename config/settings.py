def get_required_env(name: str) -> str:
    """
    Retrieve a required environment variable.
    Raises ImproperlyConfigured if the variable is missing or blank.
    Never prints or logs sensitive values.
    """
    value = os.getenv(name)
    if value is None or not value.strip():
        raise ImproperlyConfigured(
            f"The '{name}' environment variable is required and cannot be empty. "
            f"Please set it in your .env file or system environment."
        )
    return value.strip()


